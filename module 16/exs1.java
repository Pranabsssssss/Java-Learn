public class exs1 {
    public static void main(String[] args) {
        String chant = "never stop building robots";
        System.out.println("raw: " + chant);
        System.out.println("chars count: " + chant.length());
        System.out.println("fourth letter: " + chant.charAt(3));
        System.out.println("screaming: " + chant.toUpperCase());
        System.out.println("whisper: " + chant.toLowerCase());
    }
}
